/**
 * Содержимое страниц услуг: первый экран, «кому подходит», «что получите»
 * и шаги работы.
 *
 * Раньше всё это лежало прямо в семи файлах роутов литералами JSX. Формально
 * работало, а на деле означало, что самый продающий текст сайта — тот, который
 * и переписывают чаще всего, — правится только через разработчика. Ровно на это
 * владелец и пожаловался: «контент редактируется очень скудно».
 *
 * Устройство то же, что у остального контента: здесь СКЕЛЕТ и значения по
 * умолчанию, в базе — только изменённое. Пустая база не роняет страницы.
 *
 * ПОЧЕМУ ОТДЕЛЬНО ОТ `services.ts`. Каталог услуг едет в снимке контента на
 * КАЖДУЮ страницу сайта: он нужен карточкам, хабам и подвалу. А эти тексты
 * нужны ровно одной странице из семи. Положить их в каталог значило бы возить
 * девяносто лишних объектов в разметке главной, страницы работ и всех
 * остальных. Поэтому страница услуги грузит своё содержимое отдельно.
 *
 * ИКОНКИ — ключами из палитры (`data/icons.ts`), не компонентами: этот модуль
 * читает и сервер, и валидатор серверной функции.
 *
 * ЗВЁЗДОЧКИ В ЗАГОЛОВКЕ. Часть слов на первом экране покрашена акцентом.
 * Хранить в базе HTML нельзя — это дыра, поэтому выделенный кусок берётся
 * в звёздочки: «Лендинг, который *конвертирует*». Разбирает `AccentText`.
 */

