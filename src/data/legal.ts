/**
 * Что подставляется в текст. Значения собираются на странице из снимка
 * контента: реквизиты оператора — из админки, почта — из контактов.
 *
 *   {{operator}} — кто оператор: ФИО с ИНН, если заполнены, иначе название студии
 *   {{contact}}  — куда писать по вопросам данных: почта, если задана, иначе форма
 *   {{site}}     — адрес сайта
 *   {{version}}  — дата редакции
 *   {{years}}    — срок хранения заявок
 */
export type LegalVars = {
  operator: string;
  contact: string;
  site: string;
  version: string;
  years: string;
};

/** Ключи реквизитов оператора в текстах сайта. */
export const OPERATOR_TEXT_KEYS = {
  name: "legal.operator.name",
  status: "legal.operator.status",
  inn: "legal.operator.inn",
} as const satisfies Record<string, TextKey>;

/**
 * Подпись оператора для документов.
 *
 * Пока реквизиты не заполнены — название студии. Это честно ровно
 * до запуска: на боевом сайте оператором должен быть назван конкретный
 * человек или ИП, иначе субъекту данных не к кому обращаться. Админка
 * об этом напоминает в разделе «Оператор данных».
 */
export function operatorLabel(texts: Record<string, string>): string {
  const name = texts[OPERATOR_TEXT_KEYS.name]?.trim();
  if (!name) return ORGANIZATION.name;

  const status = texts[OPERATOR_TEXT_KEYS.status]?.trim();
  const inn = texts[OPERATOR_TEXT_KEYS.inn]?.trim();
  const details = [status, inn ? `ИНН ${inn}` : ""].filter(Boolean).join(", ");
  return details ? `${name} (${details})` : name;
}

/** Есть ли у оператора реквизиты — для предупреждения в админке. */
export function operatorFilled(texts: Record<string, string>): boolean {
  return Boolean(texts[OPERATOR_TEXT_KEYS.name]?.trim());
}

/**
 * Куда обращаться по вопросам данных.
 *
 * Почта — если задана в контактах. Иначе — страница контактов. НЕ форма
 * заявки: её нельзя отправить без нового согласия, а отзыв согласия,
 * требующий согласия, — абсурд. До запуска почта должна быть заполнена,
 * DEPLOY.md об этом говорит прямо.
 */
export function legalContactLabel(email: string | undefined): string {
  return email?.trim()
    ? `на почту ${email.trim()}`
    : "по контактам, указанным на странице «Контакты» Сайта";
}

/** Подстановка переменных. Неизвестный плейсхолдер остаётся виден — так опечатка заметна. */
export function fillLegal(text: string, vars: LegalVars): string {
  return text.replace(/\{\{(\w+)\}\}/g, (whole, key: string) =>
    key in vars ? vars[key as keyof LegalVars] : whole,
  );
}

