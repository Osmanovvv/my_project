import type { ReactNode } from "react";

/**
 * Надзаголовок секции — короткая строчка над крупным заголовком.
 *
 * Стиль был набран вручную двадцать один раз, и копии успели разойтись:
 * где-то потерялся `font-semibold`, где-то межбуквенное стало 0.16 вместо
 * 0.18, где-то цвет приглушили до `text-accent/80`. Разница мелкая, поймать
 * её глазами невозможно, а страницы от неё выглядят собранными по-разному.
 *
 * Теперь стиль живёт в одном месте: правка здесь меняет все секции разом,
 * и разойтись им больше негде.
 *
 * `className` — только для внешних отступов конкретной секции. Всё, что
 * касается самого начертания, менять надо тут, иначе разнобой вернётся.
 */
export function SectionEyebrow({
  children,
  className = "",
}: {
  children: ReactNode;
  className?: string;
}) {
  return (
    <p
      className={`text-[11px] uppercase tracking-[0.18em] text-accent font-semibold ${className}`.trimEnd()}
    >
      {children}
    </p>
  );
}
