import { Fragment } from "react";

/**
 * Текст, в котором часть слов выделена акцентным цветом.
 *
 * Выделение задаётся звёздочками: `Сайт, который *не теряет заявки*`.
 *
 * Почему так, а не HTML в поле ввода: HTML из базы пришлось бы вставлять
 * через `dangerouslySetInnerHTML`, и тогда любая правка в админке становится
 * потенциальным внедрением скрипта на все страницы сайта. Звёздочки же
 * разбираются в обычные React-элементы — вставить туда разметку нельзя
 * в принципе.
 *
 * Непарная звёздочка не ломает вывод: остаток строки печатается как есть.
 */
export function AccentText({ text }: { text: string }) {
  const parts = text.split("*");

  return (
    <>
      {parts.map((part, index) =>
        /* Нечётные куски — то, что стояло между звёздочками. */
        index % 2 === 1 ? (
          <span key={index} className="text-accent">
            {part}
          </span>
        ) : (
          <Fragment key={index}>{part}</Fragment>
        ),
      )}
    </>
  );
}
